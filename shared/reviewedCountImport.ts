import { z } from "zod";

export const REVIEWED_COUNT_IMPORT_LIMIT = 256 * 1024;
const nonempty = z.string().trim().min(1).max(4096);
const recordSchema = z.object({
  businessDate: z.string().regex(/^\d{4}-\d{2}-\d{2}$/),
  cameraName: z.literal("handoff"),
  storeId: z.number().int().positive(),
  status: z.literal("approved"),
  countBasis: z.literal("reviewed_unique_physical_cups"),
  cupsDetected: z.number().int().min(0).max(10000),
  uniqueCupIds: z.array(nonempty).max(10000),
  reviewedBy: nonempty,
  approvedAt: z.string().datetime({ offset: true }),
  coverage: z.enum(["partial", "complete"]),
  gapsDescription: z.string().max(10000).optional(),
  evidenceReferences: z.array(z.object({
    path: nonempty,
    sha256: z.string().regex(/^[a-f0-9]{64}$/),
  })).min(1).max(10000),
});

/** This envelope contains the exact Python json.dumps(sort_keys=True) bytes.
 * Keep them unchanged: the ordinary sender hashes those bytes for event identity.
 * No API credential, image, approval or count is generated by this parser.
 */
export function parseReviewedCountImport(text: string) {
  if (text.length > REVIEWED_COUNT_IMPORT_LIMIT) throw new Error("Count import exceeds 256 KiB");
  let input: unknown;
  try { input = JSON.parse(text); } catch { throw new Error("Invalid count import JSON"); }
  const envelope = z.object({
    schemaVersion: z.literal(1),
    intendedProcedure: z.literal("dashboard.importReviewedCameraCount"),
    recordJson: z.string().min(2).max(REVIEWED_COUNT_IMPORT_LIMIT),
  }).strict().safeParse(input);
  if (!envelope.success) throw new Error("Use the reviewed-count export from Beelink, not a snapshot or private configuration file");
  let raw: unknown;
  try { raw = JSON.parse(envelope.data.recordJson); } catch { throw new Error("Invalid reviewed record JSON"); }
  const parsed = recordSchema.safeParse(raw);
  if (!parsed.success) throw new Error("A reviewed unique-cup record with evidence and approval is required");
  const record = parsed.data;
  const date = new Date(`${record.businessDate}T00:00:00Z`);
  if (!Number.isFinite(date.getTime()) || date.toISOString().slice(0, 10) !== record.businessDate) {
    throw new Error("Invalid business date");
  }
  if (record.cupsDetected !== record.uniqueCupIds.length
    || new Set(record.uniqueCupIds).size !== record.uniqueCupIds.length) {
    throw new Error("Cup total must match distinct reviewed cup identities");
  }
  if (record.coverage === "partial" && (!record.gapsDescription?.trim() || record.cupsDetected === 0)) {
    throw new Error("Partial evidence requires a positive reviewed count and coverage limitations");
  }
  if (record.coverage === "complete" && record.gapsDescription?.trim()) {
    throw new Error("Complete coverage cannot also declare recording gaps");
  }
  return { recordJson: envelope.data.recordJson, record };
}
